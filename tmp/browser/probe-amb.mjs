import puppeteer from "puppeteer-core";
const EDGE = "C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe";
const b = await puppeteer.launch({ executablePath: EDGE, headless: "new", args: ["--no-sandbox"] });
const p = await b.newPage();
await p.setViewport({ width: 420, height: 560 });
await p.goto("http://127.0.0.1:8791/?act=probe", { waitUntil: "domcontentloaded" });
await p.waitForSelector("[data-po-card]", { timeout: 20000 });
await new Promise(r => setTimeout(r, 7000));
const a = await p.evaluate(() => { const d = window.__pixelOfficeDebug; return typeof d === "function" ? d() : "no-fn"; });
console.log("type:", typeof a);
console.log("keys:", a && typeof a === "object" ? Object.keys(a).join(",") : a);
console.log("screens:", JSON.stringify(a && a.screens));
console.log("lamps:", JSON.stringify(a && a.lamps));
console.log("clock:", JSON.stringify(a && a.clock));
await b.close();
